"""Generates the launcher icon layers and docs/logo.svg from one geometry.

A feed of three posts, cut by a trail blaze. Run from the repo root: python3 tools/make_icon.py
"""
import math

C = (54.0, 54.0)
A = math.radians(28)
GAP, BAND, BAND_LEN, SHIFT, L = 6.0, 3.8, 27, 1.8, 200

d = (math.cos(A), -math.sin(A))
n = (math.sin(A), math.cos(A))


def pt(t, s):
    return (C[0] + d[0] * t + n[0] * s, C[1] + d[1] * t + n[1] * s)


def poly(pts):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"


def bars(dx, dy):
    out = []
    # Square-cut boards, not pills, and every corner inside the 33-unit safe circle.
    for cy in (40, 54, 68):
        x0, x1, r = 31 + dx, 77 + dx, 1.5
        y0, y1 = cy - 5 + dy, cy + 5 + dy
        out.append(
            f"M{x0 + r:.2f},{y0:.2f} H{x1 - r:.2f} A{r},{r} 0 0 1 {x1 - r:.2f},{y1:.2f} "
            f"H{x0 + r:.2f} A{r},{r} 0 0 1 {x0 + r:.2f},{y0:.2f} Z"
        )
    return " ".join(out)


upper = poly([pt(-L, -GAP), pt(L, -GAP), pt(L, -L), pt(-L, -L)])
lower = poly([pt(-L, GAP), pt(L, GAP), pt(L, L), pt(-L, L)])
band = poly([pt(-BAND_LEN, -BAND), pt(BAND_LEN, -BAND), pt(BAND_LEN, BAND), pt(-BAND_LEN, BAND)])
# The two halves slide apart along the cut, like a sliced stack.
up = bars(-d[0] * SHIFT, -d[1] * SHIFT)
lo = bars(d[0] * SHIFT, d[1] * SHIFT)


def vector(bar, blaze=None):
    # The monochrome layer leaves the cut empty: a filled slash would close the gap.
    blaze_path = f'    <path android:fillColor="{blaze}" android:pathData="{band}" />\n' if blaze else ""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group>
        <clip-path android:pathData="{upper}" />
        <path android:fillColor="{bar}" android:pathData="{up}" />
    </group>
    <group>
        <clip-path android:pathData="{lower}" />
        <path android:fillColor="{bar}" android:pathData="{lo}" />
    </group>
{blaze_path}</vector>
'''


res = "app/src/main/res"
open(f"{res}/drawable/ic_launcher_foreground.xml", "w").write(vector("@color/blaze_white", "@color/blaze_red"))
open(f"{res}/drawable/ic_launcher_monochrome.xml", "w").write(vector("#FFFFFFFF"))
open(f"{res}/mipmap-anydpi/ic_launcher.xml", "w").write('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/granite" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
open("docs/logo.svg", "w").write(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="128" height="128" role="img" aria-label="Feedcut">
  <defs>
    <clipPath id="u"><path d="{upper}"/></clipPath>
    <clipPath id="l"><path d="{lower}"/></clipPath>
  </defs>
  <rect width="108" height="108" rx="24" fill="#17191A"/>
  <path clip-path="url(#u)" fill="#F4F2EC" d="{up}"/>
  <path clip-path="url(#l)" fill="#F4F2EC" d="{lo}"/>
  <path fill="#D7261E" d="{band}"/>
</svg>
''')
